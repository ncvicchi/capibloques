import assert from 'node:assert/strict';
import * as Blockly from 'blockly';
import { advanceHouseWorld, createHouseWorldState, defaultHouseEnvironment, validHouseEnvironment, houseBindings } from '../lib/house-world.ts';
import { examples, makeProject, decodeProject, validateProgramForScene, generateEsp32CodeResult, generateEspIdfCodeResult } from '../lib/capiblocks.ts';
import { createSceneFromTemplate, createEmptyScene, appendTemplateToScene, constrainSceneItemPosition, removeDeviceFromScene, addDeviceToScene, isSceneDefinition, validateScene } from '../lib/scene-model.ts';
import { registerBlocks, workspaceDevices, compileWorkspace } from '../lib/blockly-engine.ts';
import { normalizeWorkspaceTabs } from '../lib/workspace-tabs.ts';
import { createCapiRules } from '../lib/capi-rules.ts';
const run = (w, targets, seconds) => { for (let i = 0; i < seconds * 10; i++) w = advanceHouseWorld(w, targets, 100); return w; };
const initial = createHouseWorldState({ ...defaultHouseEnvironment, automaticArrivals: false });
let closed = { ...initial, pendingVisitor: 'unknown' };
closed = run(closed, {}, 40);
assert.equal(closed.entries.roja, 0); assert.equal(closed.abandoned, 1); assert.equal(closed.people.length, 0);
let open = run({ ...initial, pendingVisitor: 'unknown' }, { doorAngle: 90 }, 14);
assert.equal(open.entries.roja, 1, 'puerta abierta no verifica tarjetas');
let crossing = { ...initial, pendingVisitor: 'known' };
while (!crossing.passage) crossing = advanceHouseWorld(crossing, { doorAngle: 90 }, 100);
crossing = run(crossing, { doorAngle: 0 }, 8);
assert.equal(crossing.entries.azul, 1); assert.ok(crossing.closeWarnings >= 1, 'cerrar no corta ni congela a quien cruza');
const dark = createHouseWorldState({ ...defaultHouseEnvironment, night: true });
assert.equal(run(dark, { insideLight: 80 }, 1).insideLux, 2700);
assert.equal(run(dark, { insideLight: 80 }, 1).outsideLux, 300, 'sensor exterior mide luz natural');
let a = createHouseWorldState({ ...defaultHouseEnvironment, automaticDay: true }), b = structuredClone(a);
a = run(a, { doorAngle: 90 }, 300); b = run(b, { doorAngle: 90 }, 300);
assert.deepEqual(a, b); assert.ok(a.people.length <= 3);
assert.deepEqual(initial, createHouseWorldState({ ...defaultHouseEnvironment, automaticArrivals: false }));
for (const bad of [null, {}, { ...defaultHouseEnvironment, night: 1 }, { ...defaultHouseEnvironment, nextVisitor: 'admin' }, { ...defaultHouseEnvironment, extra: 1 }]) assert.equal(validHouseEnvironment(bad), false);
const scene = createSceneFromTemplate('smartHouse');
assert.equal(isSceneDefinition(scene), true); assert.deepEqual(validateScene(scene).issues.filter(i => i.severity === 'error'), []);
const moved = structuredClone(scene); moved.devices.find(d => d.id === 'house-bell').position = { x: 80, y: 460 };
assert.equal(houseBindings(moved).bell, 'house-bell'); assert.deepEqual(constrainSceneItemPosition(moved, { id: 'house-bell', kind: 'button' }, { x: 70, y: 450 }), { x: 70, y: 450 });
assert.equal(isSceneDefinition(removeDeviceFromScene(moved, 'house-bell')), true);
assert.equal(addDeviceToScene(scene, 'led').scene.devices.length, 14, 'luces extra libres');
const appended = appendTemplateToScene(createEmptyScene(), 'smartHouse').scene;
assert.equal(isSceneDefinition(appended), true); assert.equal(Object.keys(houseBindings(appended)).length, 11);
registerBlocks(Blockly);
for (const e of examples.filter(e => e.id.startsWith('smartHouse'))) {
  const w = new Blockly.Workspace(); workspaceDevices.set(w, e.scene.devices); Blockly.serialization.workspaces.load(structuredClone(e.workspace), w);
  const program = compileWorkspace(w); w.dispose();
  assert.deepEqual(validateProgramForScene(program, e.scene).filter(i => i.severity === 'error'), []);
  assert.deepEqual(decodeProject(JSON.parse(JSON.stringify(makeProject(e.title, e.scene, e.workspace)))).project.workspace, e.workspace);
  assert.equal(program.routines.length, e.id === 'smartHouse' ? 0 : 6);
  assert.equal(normalizeWorkspaceTabs(e.workspace).tabs.length, e.id === 'smartHouse' ? 1 : 4);
  for (const r of [generateEsp32CodeResult(program, e.title, e.scene), generateEspIdfCodeResult(program, e.title, e.scene)]) assert.deepEqual(r.diagnostics.filter(i => i.severity === 'error'), []);
  assert.ok(createCapiRules(program, e.scene, 'wemos-d1-r32').instructionCount > 0);
}
console.log('Casa: puerta, espera/retiro, paso completo, aviso de cierre, luz realimentada, azar, roles móviles y dos ejemplos/JSON/reglas aprobados.');
